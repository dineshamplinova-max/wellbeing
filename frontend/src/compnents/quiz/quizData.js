// Wellbeing quiz content. Everything here is general self-reflection, not a
// medical or psychological assessment, and no result is a diagnosis.
//
// Question types:
//   scale  - one choice from an ordered list (value = option index)
//   slider - a number between min and max
//   choice - one choice from an unordered list (not scored)
//   multi  - several choices, up to maxSelections (not scored)
//
// Scored questions name an `area`. `reverse: true` means a higher answer is
// less comfortable (e.g. "How often do you feel overwhelmed?").
// `showIf: { id, below }` asks a follow-up only when the earlier answer's
// wellbeing value (0-4, higher is better) is below `below`.
// `ack` holds scripted replies used by the guided conversation view.

